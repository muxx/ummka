CREATE TABLE sidebar_channel (
    team_id TEXT NOT NULL REFERENCES sidebar_team(team_id) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    channel_id TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('O','P','D','G')),
    name TEXT NOT NULL,
    display_name TEXT NOT NULL,
    header TEXT NOT NULL,
    purpose TEXT NOT NULL,
    delete_at INTEGER NOT NULL,
    last_post_at INTEGER,
    last_root_post_at INTEGER,
    total_msg_count INTEGER,
    total_msg_count_root INTEGER,
    last_viewed_at INTEGER,
    msg_count INTEGER,
    msg_count_root INTEGER,
    mention_count INTEGER,
    mention_count_root INTEGER,
    urgent_mention_count INTEGER,
    muted INTEGER NOT NULL CHECK (muted IN (0,1)), create_at INTEGER,
    PRIMARY KEY (team_id, position),
    UNIQUE (team_id, channel_id)
) STRICT, WITHOUT ROWID;
